import { describe, expect, it } from 'vitest';
import { parsePrusaGcode, validateConfig } from '../src/core/prusaParser.ts';
import { ePerMm } from '../src/core/toolpath.ts';
import { fixture } from './helpers.ts';

describe('PrusaSlicer parser', () => {
  it('parses a plain cylinder into one loop per layer', () => {
    const p = parsePrusaGcode(fixture('cylinder'));
    expect(p.layers.length).toBe(100);
    expect(p.layers[0].z).toBeCloseTo(0.2);
    expect(p.layers[50].height).toBeCloseTo(0.2);
    for (const l of p.layers) {
      expect(l.loops.length).toBe(1);
      expect(l.loops[0].depth).toBe(0);
      // radius 10 cylinder, wall centreline ~ 9.78
      const c = l.loops[0];
      const r = Math.hypot(c.bbox.maxX - c.bbox.minX, c.bbox.maxY - c.bbox.minY) / 2;
      expect(r).toBeGreaterThan(13.5);
      expect(r).toBeLessThan(14.2);
    }
    expect(p.config.perimeters).toBe('1');
    expect(validateConfig(p.config).errors).toEqual([]);
    expect(p.openWalls).toBe(0);
    expect(p.footer[0]).toMatch(/^M107/);
    expect(p.footer.some((l) => l.startsWith('; prusaslicer_config = begin'))).toBe(true);
    expect(p.header[0]).toMatch(/generated by PrusaSlicer/);
  });

  it('keeps machine state at the end of each layer', () => {
    const p = parsePrusaGcode(fixture('cylinder'));
    const s = p.layerEndState[2];
    expect(s.z).toBeCloseTo(0.6, 3);
    expect(s.relativeE).toBe(true);
    expect(Math.hypot(s.x - 110, s.y - 110)).toBeLessThan(11);
  });

  it('flow model matches PrusaSlicer E per mm', () => {
    const p = parsePrusaGcode(fixture('cylinder'));
    const loop = p.layers[10].loops[0];
    const calc = ePerMm(loop.width, p.layers[10].height, { filamentDiameter: 1.75, extrusionMultiplier: 1 });
    expect(loop.ePerMm).toBeDefined();
    expect(Math.abs(calc - loop.ePerMm!) / calc).toBeLessThan(0.02);
  });

  it('finds two loops per layer in a tube, inner one at depth 1', () => {
    const p = parsePrusaGcode(fixture('tube'));
    const mid = p.layers[Math.floor(p.layers.length / 2)];
    expect(mid.loops.length).toBe(2);
    expect(mid.loops.map((l) => l.depth).sort()).toEqual([0, 1]);
  });

  it('handles the Y split: one loop below, two above', () => {
    const p = parsePrusaGcode(fixture('y_split'));
    expect(p.layers[20].loops.length).toBe(1);
    expect(p.layers[150].loops.length).toBe(2);
  });
});
